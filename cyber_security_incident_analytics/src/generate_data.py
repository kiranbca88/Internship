"""
generate_data.py
----------------
Generates a reproducible, synthetic cybersecurity incident dataset for analytics.

NOTE ON DATA INTEGRITY:
All records generated by this script are entirely fictional and synthetic.
No actual corporate networks, credentials, personal data, or real vulnerabilities
are depicted. Fixed random seed ensures 100% reproducibility.
"""

import os
import random
import numpy as np
import pandas as pd
from datetime import datetime, timedelta

def generate_synthetic_incidents(num_records: int = 150, random_seed: int = 42) -> pd.DataFrame:
    """
    Generate synthetic cybersecurity incident records.

    Parameters:
        num_records (int): Number of unique incident records to generate (>= 100).
        random_seed (int): Seed for random number generators to ensure reproducibility.

    Returns:
        pd.DataFrame: Raw synthetic cybersecurity incident dataset.
    """
    random.seed(random_seed)
    np.random.seed(random_seed)

    # Categories as required
    incident_types = [
        "Phishing",
        "Malware",
        "Ransomware",
        "Suspicious Login",
        "Data Leak",
        "Unauthorized Access"
    ]
    type_weights = [0.32, 0.22, 0.08, 0.18, 0.08, 0.12]  # Phishing & Malware most common

    severities = ["Low", "Medium", "High", "Critical"]
    severity_weights = [0.25, 0.35, 0.25, 0.15]

    departments = [
        "IT",
        "Finance",
        "HR",
        "Marketing",
        "Operations",
        "Sales",
        "Legal",
        "Engineering"
    ]

    statuses = ["Resolved", "In Progress", "Open"]
    status_weights = [0.70, 0.18, 0.12]  # ~70% resolved, 30% unresolved

    # Realistic synthetic description templates per incident type
    descriptions_map = {
        "Phishing": [
            "[SYNTHETIC] Suspicious email containing fake payroll update link flagged by employee.",
            "[SYNTHETIC] Executive impersonation attempt targeting finance department for wire transfer.",
            "[SYNTHETIC] Mass credential harvesting email impersonating cloud storage login page.",
            "[SYNTHETIC] Spear phishing message with macro-enabled invoice spreadsheet attached."
        ],
        "Malware": [
            "[SYNTHETIC] Endpoint security agent quarantined Trojan downloader on workstation.",
            "[SYNTHETIC] Adware bundle detected and removed after unauthorized freeware installation.",
            "[SYNTHETIC] Cryptomining payload detected executing during off-peak processing hours.",
            "[SYNTHETIC] Malicious PowerShell script blocked by host intrusion prevention system."
        ],
        "Ransomware": [
            "[SYNTHETIC] Encrypted file extensions and ransom text note detected on staging server share.",
            "[SYNTHETIC] Ransomware dropper execution blocked in isolated sandbox test environment.",
            "[SYNTHETIC] Lateral movement attempt detected following compromised network share access."
        ],
        "Suspicious Login": [
            "[SYNTHETIC] Multiple failed MFA attempts followed by successful login from foreign ASN.",
            "[SYNTHETIC] Concurrent active sessions detected across two geographically distant locations.",
            "[SYNTHETIC] Dormant user account initiated administrative portal login outside work hours.",
            "[SYNTHETIC] Brute force authentication attempts flagged against external VPN gateway."
        ],
        "Data Leak": [
            "[SYNTHETIC] Cloud bucket containing sanitized test exports discovered with public read access.",
            "[SYNTHETIC] Outbound email containing unencrypted customer identifiers blocked by DLP.",
            "[SYNTHETIC] Unapproved third-party cloud sync client transferred internal project documentation."
        ],
        "Unauthorized Access": [
            "[SYNTHETIC] Non-admin user attempted privilege escalation via unpatched local service.",
            "[SYNTHETIC] Access granted to restricted code repository without required manager approval.",
            "[SYNTHETIC] Terminated contractor access badge and VPN token used prior to credential deprovisioning."
        ]
    }

    start_date = datetime(2024, 1, 1)
    end_date = datetime(2024, 8, 31)
    date_range_days = (end_date - start_date).days

    records = []
    for i in range(1, num_records + 1):
        inc_id = f"INC-2024-{i:04d}"
        
        # Random date distributed over several months
        offset_days = random.randint(0, date_range_days)
        offset_seconds = random.randint(0, 86399)
        inc_date = (start_date + timedelta(days=offset_days, seconds=offset_seconds)).strftime("%Y-%m-%d %H:%M:%S")

        inc_type = random.choices(incident_types, weights=type_weights)[0]
        severity = random.choices(severities, weights=severity_weights)[0]
        department = random.choice(departments)
        status = random.choices(statuses, weights=status_weights)[0]

        # Resolution hours: ONLY for resolved incidents.
        # Open and In Progress incidents MUST remain missing (NaN).
        if status == "Resolved":
            # Realistic baseline based on severity
            if severity == "Critical":
                res_hours = round(np.random.gamma(shape=4.0, scale=8.0), 1)  # ~32 hrs avg
            elif severity == "High":
                res_hours = round(np.random.gamma(shape=3.5, scale=5.0), 1)  # ~17.5 hrs avg
            elif severity == "Medium":
                res_hours = round(np.random.gamma(shape=3.0, scale=3.0), 1)  # ~9 hrs avg
            else:  # Low
                res_hours = round(np.random.gamma(shape=2.0, scale=2.0), 1)  # ~4 hrs avg
            res_hours = max(0.5, min(res_hours, 168.0))  # Bound between 30 mins and 7 days
        else:
            res_hours = np.nan

        description = random.choice(descriptions_map[inc_type])

        records.append({
            "Incident_ID": inc_id,
            "Incident_Date": inc_date,
            "Incident_Type": inc_type,
            "Severity": severity,
            "Department": department,
            "Status": status,
            "Resolution_Hours": res_hours,
            "Description": description
        })

    df = pd.DataFrame(records)

    # Intentionally introduce minor raw data anomalies for data cleaning demonstration:
    # 1. Trailing or leading whitespace in department on 3 rows
    df.loc[2, "Department"] = " IT "
    df.loc[14, "Department"] = "Finance  "
    df.loc[28, "Department"] = " HR"

    # 2. Add 2 duplicate rows at the end to demonstrate deduplication
    duplicate_rows = df.iloc[[5, 12]].copy()
    df = pd.concat([df, duplicate_rows], ignore_index=True)

    return df

def save_raw_data(df: pd.DataFrame, output_path: str) -> None:
    """Save raw dataset to CSV, ensuring parent directories exist."""
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    df.to_csv(output_path, index=False)
    print(f"[SUCCESS] Generated {len(df)} raw records (including intentional duplicates for cleaning practice).")
    print(f"[SAVED] Raw dataset stored at: {output_path}")

if __name__ == "__main__":
    # Resolve path relative to this script file
    script_dir = os.path.dirname(os.path.abspath(__file__))
    project_root = os.path.dirname(script_dir)
    raw_csv_path = os.path.join(project_root, "data", "raw", "incidents_sample.csv")
    
    print("[INFO] Generating synthetic cybersecurity incident dataset...")
    raw_df = generate_synthetic_incidents(num_records=150, random_seed=42)
    save_raw_data(raw_df, raw_csv_path)

